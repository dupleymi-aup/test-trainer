export type QuizQuestionType = "single" | "truefalse" | "multiple" | "text";

export interface QuizQuestion {
  id: string;
  type: QuizQuestionType;
  question: string;
  options: string[];  // For single, truefalse, multiple
  correctIndex: number;  // For single, truefalse (0=True, 1=False)
  correctIndices: number[];  // For multiple choice
  correctAnswer: string;  // For text input
  explanation: string;
}

// Helper to create single-choice questions
function single(id: string, question: string, options: string[], correctIndex: number, explanation: string): QuizQuestion {
  return { id, type: "single", question, options, correctIndex, correctIndices: [], correctAnswer: "", explanation };
}

// Helper to create true/false questions
function truefalse(id: string, question: string, isTrue: boolean, explanation: string): QuizQuestion {
  return { id, type: "truefalse", question, options: ["Верно", "Неверно"], correctIndex: isTrue ? 0 : 1, correctIndices: [], correctAnswer: "", explanation };
}

// Helper to create multiple-choice questions
function multiple(id: string, question: string, options: string[], correctIndices: number[], explanation: string): QuizQuestion {
  return { id, type: "multiple", question, options, correctIndex: 0, correctIndices, correctAnswer: "", explanation };
}

// Helper to create text-input questions
function text(id: string, question: string, correctAnswer: string, explanation: string): QuizQuestion {
  return { id, type: "text", question, options: [], correctIndex: 0, correctIndices: [], correctAnswer, explanation };
}

